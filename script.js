let carrito = [];
let categoriaActual = 'todos';

const formatearCOP = (valor) => {
  return new Intl.NumberFormat('es-CO', {
    style: 'currency',
    currency: 'COP',
    maximumFractionDigits: 0
  }).format(valor) + " COP";
};

document.addEventListener('DOMContentLoaded', () => {
  renderizarCategorias();
  renderizarProductos(productos);
  actualizarCarritoUI();
});

function renderizarCategorias() {
  const container = document.getElementById('categoriesContainer');
  if (!container) return;
  container.innerHTML = categorias.map(cat => `
    <button onclick="filtrarPorCategoria('${cat.id}')" class="px-5 py-2.5 rounded-full text-xs uppercase tracking-wider font-semibold whitespace-nowrap transition-all ${categoriaActual === cat.id ? 'gold-gradient-bg text-luxury-black font-bold shadow-md' : 'bg-luxury-card border border-luxury-border text-gray-400 hover:text-gold-primary hover:border-gold-primary'}">
      ${cat.nombre}
    </button>
  `).join('');
}

function filtrarPorCategoria(catId) {
  categoriaActual = catId;
  renderizarCategorias();
  const filtrados = catId === 'todos' ? productos : productos.filter(p => p.categoria === catId);
  document.getElementById('catalogTitle').innerText = catId === 'todos' ? 'Todas las Colecciones' : `Colección ${categorias.find(c => c.id === catId).nombre}`;
  renderizarProductos(filtrados);
}

