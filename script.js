function closeQuickView() {
  document.getElementById('quickViewModal').classList.add('hidden');
}

function agregarAlCarritoDesdeModal() {
  if (!productoSeleccionado) return;
  const material = productoSeleccionado.materiales[0];
  const itemExistente = carrito.find(
  item => item.id === productoSeleccionado.id &&
  item.material === material
);  

  if (itemExistente) {
    itemExistente.cantidad++;
  } else {
    carrito.push({
  id: productoSeleccionado.id,
  nombre: productoSeleccionado.nombre,
  precio: productoSeleccionado.precio,
  imagen: productoSeleccionado.imagenPrincipal,
  material: material,
  cantidad: 1
});
  }

  closeQuickView();
  actualizarCarritoUI();
  toggleCart(true);
}

function toggleCart(forceOpen = false) {
  const drawer = document.getElementById('cartDrawer');
  const overlay = document.getElementById('cartOverlay');
  if (forceOpen) {
    drawer.classList.remove('translate-x-full');
    overlay.classList.remove('hidden');
  } else {
    drawer.classList.toggle('translate-x-full');
    overlay.classList.toggle('hidden');
  }
}

function actualizarCarritoUI() {
  const count = carrito.reduce((sum, item) => sum + item.cantidad, 0);
  document.getElementById('cartCount').innerText = count;
  const container = document.getElementById('cartItems');
  const totalLabel = document.getElementById('cartTotal');

  if (carrito.length === 0) {
    container.innerHTML = `<div class="text-center py-12 text-gray-500"><p class="text-xs">Tu pedido está vacío.</p></div>`;
    totalLabel.innerText = formatearCOP(0);
    return;
  }

  let total = 0;
  container.innerHTML = carrito.map((item, index) => {
    total += item.precio * item.cantidad;
    return `
      <div class="flex items-center gap-3 p-3 bg-luxury-black border border-luxury-border rounded-lg">
        <img src="${item.imagen}" class="w-14 h-14 object-cover rounded">
        <div class="flex-1">
          <h4 class="text-xs font-semibold text-white line-clamp-1">${item.nombre}</h4>
          <p class="text-[10px] text-gold-primary">${item.material}</p>
          <p class="text-xs text-gray-300 font-bold mt-1">${formatearCOP(item.precio)}</p>
        </div>
        <div class="flex flex-col items-end gap-1">
          <div class="flex items-center gap-2 bg-luxury-card border border-luxury-border rounded px-2 py-0.5">
            <button onclick="cambiarCantidad(${index}, -1)" class="text-xs text-gray-400">-</button>
            <span class="text-xs text-white font-bold">${item.cantidad}</span>
            <button onclick="cambiarCantidad(${index}, 1)" class="text-xs text-gray-400">+</button>
          </div>
        </div>
      </div>
    `;
  }).join('');
  totalLabel.innerText = formatearCOP(total);
}

function cambiarCantidad(index, delta) {
  if (carrito[index]) {
    carrito[index].cantidad += delta;
    if (carrito[index].cantidad <= 0) carrito.splice(index, 1);
  }
  actualizarCarritoUI();
}

function checkoutWhatsApp() {
  if (carrito.length === 0) return alert("Tu carrito está vacío.");
  const telefono = document.getElementById('whatsappSelect').value;
  let mensaje = "✨ *NUEVO PEDIDO - SAVÉ DORÉ* ✨\n\nHola, me gustaría solicitar los siguientes productos:\n\n";
  let total = 0;
  carrito.forEach((item, i) => {
    total += item.precio * item.cantidad;
    mensaje += `*${i + 1}. ${item.nombre}*• Material: ${item.material}• Cantidad: ${item.cantidad}• Subtotal: ${formatearCOP(item.precio * item.cantidad)}`;
  });
  mensaje += `💰 *TOTAL ESTIMADO:* ${formatearCOP(total)}\n📍 *Ubicación:* Cali, Colombia`;
  window.open(`https://wa.me/${telefono}?text=${encodeURIComponent(mensaje)}`, '_blank');
}